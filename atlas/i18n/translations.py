def translate(language: str, key: str) -> str:
    """Return a translated string, falling back to English."""
    language = language if language in TRANSLATIONS else "en"

    return TRANSLATIONS[language].get(
        key,
        TRANSLATIONS["en"].get(key, key),
    )


def get_translations(language: str) -> dict[str, str]:
    """Return the translation dictionary for a language."""
    language = language if language in TRANSLATIONS else "en"
    return TRANSLATIONS[language].copy()
